#!/usr/bin/env python3
"""Generates iOS TestIDs.swift and docs/test-ids.md from the Android TestTags catalogue.

Android's `TestTags.kt` is the single source of automation identifiers; this keeps iOS identical.
Run from the repository root: `python3 tools/generate_test_ids.py` (add `--check` in CI).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "android/core/ui/src/main/kotlin/com/mobiletestplayground/core/ui/TestTags.kt"
TARGET = ROOT / "ios/MobileTestPlayground/UI/TestIDs.swift"
DOC = ROOT / "docs/test-ids.md"

DOC_HEADER = """# Automation identifiers

Generated by `tools/generate_test_ids.py` from
`android/core/ui/src/main/kotlin/com/mobiletestplayground/core/ui/TestTags.kt`. Do not edit by hand.

The same identifiers exist on Android (Compose `Modifier.testTag`, exposed to UIAutomator as resource
ids through `testTagsAsResourceId`) and iOS (`.accessibilityIdentifier`, in `TestIDs.swift`).

Rules: lowercase `snake_case`; independent of visible text and locale; unique among elements visible
at the same time; stable between launches. Screen roots end in `_screen` (or are the screen name for
admin screens). Error labels are the field id plus `_error`.

**Every element has an ID.** Each element that shows content or reacts to input (text, image, input
field, button, toggle, progress, scroll container) carries one, on both platforms. Text and icons
inside an identified control belong to that control. The audit tests `IdentifierCoverageTest`
(Android) and `IdentifierCoverageUITests` (iOS) open every screen and state and fail on any element
without an ID; see [automation.md](automation.md#identifier-coverage).

Derived IDs follow fixed rules, so they need no catalogue entry and are the same on both platforms:

| Element | Rule | Example |
|---|---|---|
| Static text from the shared string table (heading, label, help text) | `<string key>_text` | `login_heading_text` |
| A screen's scroll container | `<screen>_scroll` (screen ID without `_screen`) | `login_scroll` |
| Label of a label/value row | `<value id>_label` | `profile_email_label` |
| Title inside a tagged container (card, section, dialog, sheet, target) | `<container id>_title` | `scroll_card_01_title` |
| Body text inside a tagged dialog or sheet | `<container id>_message` | `dialog_warning_message` |

Where a platform renders an element with a system control that cannot carry an identifier, the
difference is listed in [automation.md](automation.md#platform-differences).

"""


def camel(name: str) -> str:
    parts = name.lower().split("_")
    return parts[0] + "".join(p.title() for p in parts[1:])


def render() -> str:
    src = SOURCE.read_text(encoding="utf-8")
    consts = re.findall(r'const val ([A-Z0-9_]+) = "([a-z0-9_]+)"', src)
    funcs = re.findall(r"fun ([a-zA-Z0-9]+)\(([a-zA-Z]+): (String|Int)\) = (.+)", src)
    out = [
        "// Generated by tools/generate_test_ids.py from the Android TestTags catalogue. Do not edit.",
        "// The same automation identifiers on both platforms; see docs/test-ids.md.",
        "",
        "enum TestIDs {",
    ]
    out += [f'    static let {camel(name)} = "{value}"' for name, value in consts]
    out.append("")
    for name, arg, typ, body in funcs:
        body = body.strip()
        literal = re.match(r'^"(.*)"$', body)
        if body == arg:
            expr = arg
        elif literal:
            text = re.sub(r"\$\{([^}]+)\}", r"\\(\1)", literal.group(1))
            expr = '"' + re.sub(r"\$([a-zA-Z]+)", r"\\(\1)", text) + '"'
        elif "padStart(" in body:
            prefix = re.match(r'"([a-z_]+)"', body).group(1)
            width = re.search(r"padStart\((\d+)", body).group(1)
            expr = f'"{prefix}" + String(format: "%0{width}d", {arg})'
        else:
            raise SystemExit(f"unhandled TestTags function: {name} = {body}")
        out.append(f"    static func {name}(_ {arg}: {typ}) -> String {{ {expr} }}")
    out += ["}", ""]
    return "\n".join(out)


def humanize(name: str, section: str) -> str:
    words = name.lower().split("_")
    prefixes = [w.lower() for w in re.findall(r"[A-Za-z0-9]+", section)]
    while len(words) > 1 and words[0] in prefixes + ["a11y", "nav", "dynamic", "content", "scroll", "gesture", "form"]:
        words = words[1:]
    return " ".join(words).capitalize()


def render_doc() -> str:
    src = SOURCE.read_text(encoding="utf-8")
    lines = [DOC_HEADER, "| Screen | Element | Automation ID |", "|---|---|---|"]
    section = "General"
    for raw in src.splitlines():
        heading = re.match(r"\s*// --- (.+) ---", raw)
        if heading:
            section = heading.group(1)
            continue
        const = re.match(r'\s*const val ([A-Z0-9_]+) = "([a-z0-9_]+)"', raw)
        if const:
            lines.append(f"| {section} | {humanize(const.group(1), section)} | `{const.group(2)}` |")
            continue
        func = re.match(r"\s*fun ([a-zA-Z0-9]+)\(([a-zA-Z]+): (String|Int)\) = (.+)", raw)
        if func:
            name, arg, _, body = func.groups()
            literal = re.match(r'^"(.*)"$', body.strip())
            if body.strip() == arg:
                pattern = f"<{arg}>"
            elif literal:
                pattern = re.sub(r"\$\{?([a-zA-Z]+)\}?", r"<\1>", literal.group(1))
            else:
                prefix = re.match(r'"([a-z_]+)"', body.strip()).group(1)
                width = re.search(r"padStart\((\d+)", body).group(1)
                pattern = prefix + "<" + arg + ", " + width + " digits>"
            readable = re.sub(r"([A-Z])", r" \1", name).lower().capitalize()
            lines.append(f"| {section} | {readable} (pattern) | `{pattern}` |")
    return "\n".join(lines) + "\n"


def main() -> int:
    outputs = {TARGET: render(), DOC: render_doc()}
    if "--check" in sys.argv:
        stale = [p for p, c in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != c]
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"wrote {path.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
