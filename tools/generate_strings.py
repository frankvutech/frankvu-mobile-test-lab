#!/usr/bin/env python3
"""Generates Android and iOS string resources from shared/strings/strings.json.

One source keeps both platforms and both locales (en, de) in step. Run from the repository root:

    python3 tools/generate_strings.py          # write the files
    python3 tools/generate_strings.py --check  # exit 1 if any generated file is out of date (CI)

Outputs:
    android/app/src/main/res/values/strings.xml           (+ values-de)
    ios/MobileTestPlayground/Resources/en.lproj/Localizable.strings      (+ de.lproj)
    ios/MobileTestPlayground/Resources/en.lproj/Localizable.stringsdict  (+ de.lproj)
"""
import json
import re
import sys
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "shared" / "strings" / "strings.json"
LOCALES = ["en", "de"]
HEADER = "Generated by tools/generate_strings.py from shared/strings/strings.json. Do not edit."


def android_escape(text: str) -> str:
    text = escape(text)
    text = text.replace("'", "\\'").replace('"', '\\"')
    if text.startswith("@") or text.startswith("?"):
        text = "\\" + text
    return text


def ios_format(text: str) -> str:
    text = re.sub(r"%(\d+)\$s", r"%\1$@", text)
    text = re.sub(r"%(\d+)\$d", r"%\1$ld", text)
    return text


def ios_escape(text: str) -> str:
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")


def android_files(data):
    files = {}
    for index, locale in enumerate(LOCALES):
        lines = ['<?xml version="1.0" encoding="utf-8"?>', f"<!-- {HEADER} -->", "<resources>"]
        for name, values in data["strings"].items():
            lines.append(f'    <string name="{name}">{android_escape(values[index])}</string>')
        for name, forms in data["plurals"].items():
            lines.append(f'    <plurals name="{name}">')
            for quantity, text in forms[locale].items():
                lines.append(f'        <item quantity="{quantity}">{android_escape(text)}</item>')
            lines.append("    </plurals>")
        lines.append("</resources>")
        folder = "values" if locale == "en" else f"values-{locale}"
        files[ROOT / "android" / "app" / "src" / "main" / "res" / folder / "strings.xml"] = "\n".join(lines) + "\n"
    return files


def ios_files(data):
    files = {}
    base = ROOT / "ios" / "MobileTestPlayground" / "Resources"
    for index, locale in enumerate(LOCALES):
        lines = [f"/* {HEADER} */", ""]
        for name, values in data["strings"].items():
            lines.append(f'"{name}" = "{ios_escape(ios_format(values[index]))}";')
        files[base / f"{locale}.lproj" / "Localizable.strings"] = "\n".join(lines) + "\n"

        plist = [
            '<?xml version="1.0" encoding="UTF-8"?>',
            f"<!-- {HEADER} -->",
            '<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
            '<plist version="1.0">',
            "<dict>",
        ]
        for name, forms in data["plurals"].items():
            plist += [
                f"    <key>{name}</key>",
                "    <dict>",
                "        <key>NSStringLocalizedFormatKey</key>",
                "        <string>%#@count@</string>",
                "        <key>count</key>",
                "        <dict>",
                "            <key>NSStringFormatSpecTypeKey</key>",
                "            <string>NSStringPluralRuleType</string>",
                "            <key>NSStringFormatValueTypeKey</key>",
                "            <string>ld</string>",
            ]
            for quantity, text in forms[locale].items():
                plist += [f"            <key>{quantity}</key>", f"            <string>{escape(ios_format(text))}</string>"]
            plist += ["        </dict>", "    </dict>"]
        plist += ["</dict>", "</plist>"]
        files[base / f"{locale}.lproj" / "Localizable.stringsdict"] = "\n".join(plist) + "\n"
    return files


def main() -> int:
    data = json.loads(SOURCE.read_text(encoding="utf-8"))
    for name, values in data["strings"].items():
        if len(values) != len(LOCALES):
            print(f"{name}: expected {len(LOCALES)} translations", file=sys.stderr)
            return 1
    outputs = {**android_files(data), **ios_files(data)}
    check = "--check" in sys.argv
    stale = []
    for path, content in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                stale.append(path)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding="utf-8")
    if stale:
        for path in stale:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        return 1
    if not check:
        print(f"wrote {len(outputs)} files")
    return 0


if __name__ == "__main__":
    sys.exit(main())
